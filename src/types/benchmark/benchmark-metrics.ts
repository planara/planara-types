/** Метрики прохождения тестирования */
export type BenchmarkMetrics = {
  /** Фактическая длительность выполнения теста в миллисекундах */
  durationMs: number;

  /** Количество отрисованных кадров за время выполнения теста */
  frames: number;

  /** Среднее количество кадров в секунду */
  averageFps: number;

  /** Минимальное количество кадров в секунду за время выполнения теста */
  minFps: number;

  /** Среднее время отрисовки одного кадра в миллисекундах */
  averageFrameTime: number;

  /** Максимальное время отрисовки одного кадра в миллисекундах */
  maxFrameTime: number;

  /** Количество объектов, участвующих в тестовой сцене */
  objectsCount: number;

  /** Количество вызовов отрисовки за кадр */
  drawCalls: number;

  /** Количество треугольников, отрисованных в сцене */
  triangles: number;

  /** Количество геометрий, загруженных в память рендерера */
  geometries: number;

  /** Количество текстур, загруженных в память рендерера */
  textures: number;

  /** Используемый объем памяти в мегабайтах, если доступен в текущем браузере */
  memoryUsedMb?: number;
};
